-- 1. Create Tables
CREATE TABLE IF NOT EXISTS public.district_references (
    id integer NOT NULL,
    district_id character varying(10) NOT NULL,
    population_2020 integer NOT NULL,
    land_area_sqkm double precision NOT NULL,
    barangay_count integer NOT NULL,
    density_persons_ha double precision NOT NULL,
    CONSTRAINT district_references_pkey PRIMARY KEY (id),
    CONSTRAINT district_references_district_id_key UNIQUE (district_id)
);

CREATE TABLE IF NOT EXISTS public.users (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    email character varying(120) NOT NULL,
    password_hash character varying(255) NOT NULL,
    role character varying(50) NOT NULL,
    name character varying(120) NOT NULL,
    title character varying(120) NOT NULL,
    organization character varying(150),
    location character varying(150) NOT NULL,
    avatar text,
    created_at timestamp without time zone NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT ix_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS public.forecast_logs (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    user_id integer,
    district character varying(50) NOT NULL,
    selected_barangays json,
    prediction_method character varying(50) NOT NULL,
    rain_now character varying(50),
    city_cases_now character varying(50),
    sim_waste character varying(50),
    sim_water character varying(50),
    sim_flood character varying(50),
    predicted_cases double precision,
    risk_level character varying(50),
    confidence double precision,
    created_at timestamp without time zone NOT NULL,
    CONSTRAINT forecast_logs_pkey PRIMARY KEY (id),
    CONSTRAINT forecast_logs_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.users(id)
);

CREATE TABLE IF NOT EXISTS public.weekly_dengue_observations (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    year integer NOT NULL,
    week_number integer NOT NULL,
    district character varying(50) NOT NULL,
    barangay character varying(120),
    case_count integer NOT NULL,
    CONSTRAINT weekly_dengue_observations_pkey PRIMARY KEY (id)
);

